const fs = require('node:fs');
const path = require('node:path');
const base = path.resolve(__dirname, '..');
const catalogs = {};
for (const locale of fs.readdirSync(path.join(base, '_locales')).sort()) {
  catalogs[locale] = JSON.parse(fs.readFileSync(path.join(base, '_locales', locale, 'messages.json'), 'utf8'));
}
fs.writeFileSync(path.join(base, 'locales.js'), '// Generated by scripts/build-locales.cjs. Edit _locales instead.\n' +
  'globalThis.ABLoopMessages = ' + JSON.stringify(catalogs, null, 2) + ';\n');
